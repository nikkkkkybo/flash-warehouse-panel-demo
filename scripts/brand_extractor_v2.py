def norm_existing_brand(b):
    """归一化原品牌值：去括号英文，空/其他品牌 → ''"""
    if not isinstance(b, str):
        return ''
    s = b.strip()
    if s in ('', 'nan', 'NaN', '其他品牌', '无'):
        return ''
    s = re.sub(r"[(（][^()（）]*[)）]", "", s).strip()
    return s


def extract_brand_v2(name, existing_brand=''):
    """
    品牌抽取 v2
    返回 (品牌, 来源)
    来源: '原值' / '词典命中' / '未命中'
    """
    # 1. 原值优先（但原值在黑名单中也跳过，如"优选"不是品牌）
    ex = norm_existing_brand(existing_brand)
    if ex and ex not in ALL_BLACKLIST:
        return ex, '原值'

    if not isinstance(name, str) or not name.strip():
        return '', '未命中'

    text = name.strip()

    # 2. 去掉开头括号内容，取品牌候选区
    # 模式：（品类词）品牌+描述
    cleaned = re.sub(r'^[（(][^()（）]*[)）]\s*', '', text)

    # 3. 词典最长匹配：在cleaned开头查找品牌
    # 按长度降序匹配，避免"雷士"抢先匹配"雷士照明"
    for brand in sorted(BRAND_DICT, key=len, reverse=True):
        if cleaned.startswith(brand):
            # 检查匹配到的词是否在黑名单（理论上词典里没有黑名单词，但双重保险）
            if brand in ALL_BLACKLIST:
                continue
            return brand, '词典命中'

    # 4. 词典不中，尝试在完整商品名中查找品牌（有些品名品牌不在开头）
    for brand in sorted(BRAND_DICT, key=len, reverse=True):
        if brand in text:
            if brand in ALL_BLACKLIST:
                continue
            return brand, '词典命中'

    return '', '未命中'
